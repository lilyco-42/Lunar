void oled_init(void)
{
    // SSD1306 init sequence for 128x64
    // Caller must have already initialized the I2C bus.
    send_cmd(0xAE); // display off
    send_cmd(0xD5); send_cmd(0x80); // clock div ratio
    send_cmd(0xA8); send_cmd(0x3F); // mux ratio = 63
    send_cmd(0xD3); send_cmd(0x00); // display offset = 0
    send_cmd(0x40); // start line = 0
    send_cmd(0x8D); send_cmd(0x14); // charge pump on
    send_cmd(0x20); send_cmd(0x00); // horizontal addressing
    send_cmd(0xA1); // segment remap (left-right flip)
    send_cmd(0xC8); // COM scan dir (bottom-up flip)
    send_cmd(0xDA); send_cmd(0x12); // COM pins HW config
    send_cmd(0x81); send_cmd(0xCF); // contrast
    send_cmd(0xD9); send_cmd(0xF1); // pre-charge period
    send_cmd(0xDB); send_cmd(0x40); // VCOMH deselect level
    send_cmd(0xA4); // resume from sleep
    send_cmd(0xA6); // normal (non-inverted)
    send_cmd(0x2E); // deactivate scroll
    send_cmd(0xAF); // display on

    oled_clear();
    ESP_LOGI(TAG, "SSD1306 initialized, I2C addr 0x%02X", OLED_I2C_ADDR);
}

void oled_clear(void)
{
    for (int page = 0; page < 8; page++) {
        set_page_addr(page, 0);
        uint8_t zeros[128] = {0};
        send_data(zeros, 128);
    }
}

void oled_show_text(int line, const char *text)
{
    if (line < 0 || line > 7) return;

    uint8_t buf[128];
    memset(buf, 0, sizeof(buf));

    int col = 0;
    while (*text && col < 128) {
        int idx = (unsigned char)*text - 0x20;
        if (idx >= 0 && idx < 96) {
            for (int i = 0; i < 5 && col < 128; i++) {
                buf[col++] = font5x7[idx][i];
            }
            // 1-pixel inter-char gap
            if (col < 128) col++;
        }
        text++;
    }

    set_page_addr(line, 0);
    send_data(buf, 128);
}

void oled_show_two_lines(const char *line1, const char *line2)
{
    oled_show_text(0, line1);
    oled_show_text(1, line2);
}

/*
 * Render a 16x16 glyph stored in SSD1306-native page format:
 *   glyph[0..15]:  top page (rows 0-7), 16 columns, bit0 = top of page
 *   glyph[16..31]: bottom page (rows 8-15), 16 columns
 */
void oled_show_glyph16(int page, int col, const uint8_t glyph[32])
{
    set_page_addr(page, col);
    send_data(glyph, 16);

    set_page_addr(page + 1, col);
    send_data(glyph + 16, 16);
}

void oled_write_bitmap(int page, int col, const uint8_t *data, int len)
{
    int bytes_per_page = 128 - col;
    if (bytes_per_page <= 0) return;

    while (len > 0 && page < 8) {
        int chunk = len;
        if (chunk > bytes_per_page) chunk = bytes_per_page;
        set_page_addr(page, col);
        send_data(data, chunk);
        data += chunk;
        len -= chunk;
        page++;
        col = 0;
        bytes_per_page = 128;
    }
}

