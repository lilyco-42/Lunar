/* Decode one UTF-8 code point (1-4 bytes), advance *s */
static uint32_t utf8_next(const char **s)
{
    const uint8_t *p = (const uint8_t *)*s;
    uint32_t cp;

    if (*p < 0x80) {
        (*s)++;
        return *p;
    }
    if ((*p & 0xE0) == 0xC0 && (p[1] & 0xC0) == 0x80) {
        cp = (*p & 0x1F) << 6 | (p[1] & 0x3F);
        *s += 2;
        return cp;
    }
    if ((*p & 0xF0) == 0xE0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80) {
        cp = (*p & 0x0F) << 12 | (p[1] & 0x3F) << 6 | (p[2] & 0x3F);
        *s += 3;
        return cp;
    }
    if ((*p & 0xF8) == 0xF0 && (p[1] & 0xC0) == 0x80 && (p[2] & 0xC0) == 0x80 && (p[3] & 0xC0) == 0x80) {
        cp = (*p & 0x07) << 18 | (p[1] & 0x3F) << 12 | (p[2] & 0x3F) << 6 | (p[3] & 0x3F);
        *s += 4;
        return cp;
    }
    (*s)++;
    return 0;
}

int oled_show_utf8(int page, const char *text, int max_width)
{
    int col = 0;
    const char *p = text;

    while (*p && (max_width == 0 || col < max_width)) {
        uint32_t cp = utf8_next(&p);
        if (cp == 0) continue;

        if (cp < 0x80) {
            /* ASCII — render inline (5px + 1px gap) */
            int idx = (int)cp - 0x20;
            if (idx >= 0 && idx < 96 && col + 6 <= 128) {
                uint8_t buf[6];
                for (int i = 0; i < 5; i++) buf[i] = font5x7[idx][i];
                buf[5] = 0; /* inter-char gap */
                set_page_addr(page, col);
                send_data(buf, 6);
                col += 6;
            } else {
                col += 6;
            }
        } else {
            /* Try Chinese font lookup */
            int gi = cn_font_lookup(cp);
            if (gi >= 0 && page < 7 && col + 16 <= 128) {
                oled_show_glyph16(page, col, cn_font_16x16[gi]);
                col += 17; /* 16px glyph + 1px gap */
            } else {
                /* Fallback: show '?' */
                col += 6;
            }
        }
    }
    return col;
}
