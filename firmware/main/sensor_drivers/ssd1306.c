// ────────────────────────────────────────────────────
// I2C helpers  (caller must init I2C bus first)
// ────────────────────────────────────────────────────
static void send_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    i2c_master_write_to_device(I2C_MASTER_PORT, OLED_I2C_ADDR,
                               buf, 2, pdMS_TO_TICKS(100));
}

static void send_data(const uint8_t *data, size_t len)
{
    if (len == 0) return;
    uint8_t *buf = malloc(len + 1);
    if (!buf) return;
    buf[0] = 0x40;
    memcpy(buf + 1, data, len);
    i2c_master_write_to_device(I2C_MASTER_PORT, OLED_I2C_ADDR,
                               buf, len + 1, pdMS_TO_TICKS(100));
    free(buf);
}

static void set_page_addr(uint8_t page, uint8_t col)
{
    send_cmd(0xB0 | (page & 0x07));   // set page
    send_cmd(0x00 | (col & 0x0F));    // set lower column
    send_cmd(0x10 | ((col >> 4) & 0x0F)); // set higher column
}

