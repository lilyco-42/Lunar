/* ─── Public API ─── */

void oled_emoji_show(emoji_t e)
{
    if (e >= EMOJI_COUNT) return;
    oled_write_bitmap(0, 0, _builtin[e], 128);
}

void oled_emoji_clear(void)
{
    uint8_t z[128] = {0};
    for (int p = 0; p < 4; p++) {
        oled_write_bitmap(p, 0, z, 128);
    }
}

void oled_emoji_register(int id, const uint8_t data[128])
{
    if (id < 0 || id >= 16) return;
    memcpy(custom_emoji[id].data, data, 128);
    custom_emoji[id].used = 1;
}

void oled_emoji_show_custom(int id)
{
    if (id < 0 || id >= 16 || !custom_emoji[id].used) return;
    oled_write_bitmap(0, 0, custom_emoji[id].data, 128);
}
